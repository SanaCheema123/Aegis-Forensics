import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import path from 'node:path'

test('rule metadata, filters, exact highlighted source and responsive details',async({page,request})=>{
  const failures:string[]=[];page.on('pageerror',error=>failures.push(error.message))
  await page.goto('/rules')
  await expect(page.getByRole('heading',{name:'Detection rule library'})).toBeVisible()
  await expect(page.locator('.detection-rule-card')).toHaveCount(9)
  await expect(page.locator('.highlighted-source')).toHaveCount(0)
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/rules_redesign_dark.png',fullPage:true})
  await page.getByLabel('Severity',{exact:true}).selectOption('Critical')
  for(const card of await page.locator('.detection-rule-card').all())await expect(card.getByText('Critical',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Clear filters'}).click()
  await page.getByLabel('Search detection rules').fill('Credential_Dumping_Tools')
  await expect(page.locator('.detection-rule-card')).toHaveCount(1)
  await expect(page.getByText('Mimikatz-style commands or LSASS dumping',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'View Rule Details: Credential_Dumping_Tools',exact:true}).click()
  const dialog=page.getByRole('dialog')
  const source=dialog.locator('details.source-section')
  await expect(source).not.toHaveAttribute('open')
  await source.locator('summary').click()
  const files=(await (await request.get('/api/v1/rules')).json()).items
  expect(await dialog.locator('.highlighted-source').textContent()).toBe(files.find((file:any)=>file.name==='credential_theft.yar').content)
  await expect(dialog.locator('.syntax-keyword').first()).toBeVisible()
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/rule_details_redesign.png',fullPage:true})
  await page.getByRole('button',{name:'Close details'}).click()
  await page.getByLabel('Search detection rules').fill('no-rule-matches-this-input')
  await expect(page.getByText('No matching rules',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Clear filters'}).first().click()
  await page.getByRole('button',{name:'Toggle theme'}).click()
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/rules_redesign_mobile_light.png',fullPage:true})
  expect(failures).toEqual([])
})

test('real evaluation analytics, matrix interaction, comparable models and evidence isolation',async({page,request})=>{
  const failures:string[]=[];page.on('pageerror',error=>failures.push(error.message))
  const health=await (await request.get('/api/v1/health')).json()
  const headers={'X-Aegis-Token':health.csrf_token}
  expect((await request.post('/api/v1/cases',{headers,data:{case_id:'ANALYTICS-UI'}})).status()).toBe(201)
  const uploaded=await request.post('/api/v1/cases/ANALYTICS-UI/evidence',{headers,multipart:{file:{name:'UNSW_NB15_demo_balanced.csv',mimeType:'text/csv',buffer:readFileSync(path.resolve('../data/training/UNSW_NB15_demo_balanced.csv'))}}})
  expect(uploaded.status()).toBe(201)
  await page.goto('/evaluation')
  await page.getByLabel('Current case').selectOption('ANALYTICS-UI')
  await expect(page.getByText('Your next evaluation, clearly explained.',{exact:true})).toBeVisible()
  await expect(page.locator('.performance-kpi')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Run labeled evaluation',exact:true})).toBeDisabled()
  await page.getByLabel('This is an explicitly labeled evaluation dataset with valid 0/1 ground truth.').check()
  await page.getByRole('button',{name:'Run labeled evaluation',exact:true}).click()
  await expect(page.locator('.performance-kpi').filter({hasText:'Accuracy'}).getByText('96.50',{exact:false})).toBeVisible({timeout:60000})
  await expect(page.getByRole('button',{name:'FP: 6 false positive records'})).toBeVisible()
  await page.getByRole('button',{name:'FP: 6 false positive records'}).click()
  await expect(page.locator('.matrix-explanation')).toContainText('Normal-labeled records flagged for review.')
  await expect(page.getByRole('img',{name:/Decision outcomes/})).toBeVisible()
  await expect(page.locator('.evaluation-visuals .recharts-bar-rectangle').first()).toBeVisible()
  await expect(page.getByText('Demonstration sample',{exact:true})).toBeVisible()
  await expect(page.locator('.evaluation-expert details')).not.toHaveAttribute('open')
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/evaluation_redesign_xgboost.png',fullPage:true})
  await page.locator('.configuration-panel summary').click()
  await page.getByLabel('Checkpoint model').selectOption('iforest')
  await expect(page.getByText(/Results below still describe the completed XGBoost/)).toBeVisible()
  await page.getByRole('button',{name:'Run labeled evaluation',exact:true}).click()
  await expect(page.locator('.performance-kpi').filter({hasText:'Accuracy'})).toContainText('68.50',{timeout:60000})
  await expect(page.locator('.model-comparison table')).toBeVisible()
  await expect(page.locator('.model-comparison table')).toContainText('96.50%')
  await expect(page.locator('.model-comparison table')).toContainText('68.50%')
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/evaluation_redesign_comparison_dark.png',fullPage:true})
  await page.getByRole('button',{name:'Toggle theme'}).click()
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/evaluation_redesign_comparison_light.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.evaluate(()=>window.scrollTo(0,0))
  await page.screenshot({path:'../audit_artifacts/evaluation_redesign_mobile.png',fullPage:true})
  expect((await request.post('/api/v1/cases/ANALYTICS-UI/evidence',{headers,multipart:{file:{name:'different.csv',mimeType:'text/csv',buffer:Buffer.from('label,message\n0,hello\n1,world\n')}}})).status()).toBe(201)
  await page.reload()
  await expect(page.getByText('Your next evaluation, clearly explained.',{exact:true})).toBeVisible()
  await expect(page.locator('.performance-kpi')).toHaveCount(0)
  // A real schema failure must remain an error, never populated placeholder metrics.
  const options=await page.getByLabel('Source evidence').locator('option').allTextContents()
  const different=options.find(name=>name==='different.csv')
  expect(different).toBeTruthy()
  await page.getByLabel('Source evidence').selectOption({label:'different.csv'})
  await page.getByLabel('This is an explicitly labeled evaluation dataset with valid 0/1 ground truth.').check()
  await page.getByRole('button',{name:'Run labeled evaluation',exact:true}).click()
  await expect(page.getByRole('alert')).toBeVisible({timeout:60000})
  await expect(page.locator('.performance-kpi')).toHaveCount(0)
  expect(failures).toEqual([])
})
